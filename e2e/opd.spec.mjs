  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:testInfo.outputPath('opd-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Save OPD registration',exact:true}).click();
  await expect(page.locator('#opd-detail')).toBeVisible();
  const uid=await page.locator('.uid-label').textContent();
  await expect(page.locator('#opd-detail')).toContainText('Test follow-up');
  await page.getByRole('button',{name:'OPD form / PDF',exact:true}).click();
  await expect(page.locator('#opd-print')).toBeVisible();
  await expect(page.locator('#opd-paper')).toContainText('OPD REGISTRATION');
  await expect(page.locator('#opd-paper')).toContainText('Munshipuliya, Lucknow, Uttar Pradesh');
  await expect(page.locator('#opd-paper')).toContainText('Dr. Saurabh Mishra');
  await expect(page.locator('#opd-paper')).toContainText('Test follow-up');
  await expect(page.locator('#opd-paper')).not.toContainText('Short note');
  expect(await page.locator('#opd-paper img').evaluate(img=>img.complete&&img.naturalWidth>0)).toBe(true);
  await page.emulateMedia({media:'print'});
  await expect(page.locator('#opd-paper')).toBeVisible();await expect(page.locator('#detail')).toBeHidden();
  await expect(page.locator('#opd-detail')).toBeHidden();await expect(page.locator('.topbar')).toBeHidden();
  await page.pdf({path:testInfo.outputPath('opd-registration.pdf'),format:'A4',printBackground:true,displayHeaderFooter:false});
  await page.emulateMedia({media:'screen'});
  await page.getByRole('button',{name:'Back to OPD visit',exact:true}).click();
  await page.getByRole('button',{name:'Create invoice',exact:true}).click();
  await expect(page.locator('#invoice-opd-notice')).toBeVisible();
  await expect(page.locator('#invoice-form [name=patient_name]')).toHaveValue('Browser Test Patient');
  await expect(page.locator('#registration')).toHaveValue(uid);
  await expect(page.locator('#opd-invoice-payment')).toContainText('590.00');
  await expect(page.locator('.locked-charge .unit-price')).toBeDisabled();
